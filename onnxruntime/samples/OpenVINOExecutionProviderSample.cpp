int main(int argc, char** argv) {
  const std::string device_type = argc > 1 ? argv[1] : "CPU";

  std::cout << "ONNX Runtime version: " << Ort::GetVersionString() << '\n';
  std::cout << "Available providers:";
  for (const auto& provider : Ort::GetAvailableProviders()) {
    std::cout << ' ' << provider;
  }
  std::cout << "\nOpenVINO device_type: " << device_type << std::endl;

  try {
    Ort::Env env{ORT_LOGGING_LEVEL_WARNING, "openvino-ep-reproducer"};
    Ort::SessionOptions options;
    options.SetIntraOpNumThreads(1);
    options.SetGraphOptimizationLevel(GraphOptimizationLevel::ORT_ENABLE_EXTENDED);
    options.AppendExecutionProvider_OpenVINO_V2({{"device_type", device_type}});

    Ort::Session session{env, kIdentityModel.data(), kIdentityModel.size(), options};
    std::cout << "Session creation succeeded." << std::endl;
  } catch (const Ort::Exception& exception) {
    std::cerr << "Session creation failed: " << exception.what() << std::endl;
    return 1;
  }

  return 0;
}
